/*
 * Printable report of one session: its votes, totals and (for normal votes) who voted.
 * "Print / Save as PDF" uses the browser's own print dialog, which renders every character (ș, ț, ă ...) correctly.
 * It shows only what the signed-in user can already see: totals only for closed votes, and no names at all
 * for anonymous votes.
 */

const when = (iso) => (iso ? new Date(iso).toLocaleString() : '—');

function nameList(title, names) {
  return el('div', {}, el('strong', {}, title + ' (' + names.length + '): '),
    names.length ? names.join(', ') : 'nobody');
}

function totals(results) {
  const rows = Object.entries(CHOICE_LABELS).map(([key, label]) => {
    const n = results.tally[key] ?? 0;
    const percent = results.total ? Math.round((n * 100) / results.total) + '%' : '—';
    return el('tr', {}, el('td', {}, label), el('td', {}, String(n)), el('td', { class: 'meta' }, percent));
  });
  return el('table', { class: 'tally' }, ...rows,
    el('tr', {}, el('td', {}, el('strong', {}, 'Total')), el('td', {}, el('strong', {}, String(results.total))), el('td', {})));
}

async function pollSection(p) {
  const closed = p.status === 'CLOSED';
  const parts = [
    el('h2', {}, p.title, p.anonymous ? el('span', { class: 'badge anon', style: 'margin-left:.5rem' }, 'Anonymous') : null,
      el('span', { class: 'badge ' + (closed ? 'closed' : 'open'), style: 'margin-left:.5rem' }, closed ? 'Closed' : 'Open')),
    p.description ? el('div', { class: 'meta' }, p.description) : null,
    el('div', {}, p.votedCount + ' of ' + p.eligibleCount + ' have voted'),
  ];
  if (!closed) {
    parts.push(el('div', { class: 'meta' }, 'Results are hidden until the vote is closed.'));
  } else {
    parts.push(totals(await api.get('/api/polls/' + p.id + '/results')));
    if (p.anonymous) {
      parts.push(el('div', { class: 'meta' }, 'Anonymous vote: who voted is not recorded in this report.'));
    } else {
      const who = await api.get('/api/polls/' + p.id + '/participation');
      parts.push(el('div', { class: 'names' }, nameList('Voted', who.voted), nameList('Did not vote', who.notVoted)));
    }
  }
  return el('section', { class: 'poll' }, ...parts);
}

(async function main() {
  const me = await initPage();
  const report = document.getElementById('report');
  const id = new URLSearchParams(location.search).get('session');
  if (!id) { report.textContent = 'No session selected.'; return; }

  try {
    const session = await api.get('/api/sessions/' + encodeURIComponent(id));
    const polls = (await api.get('/api/polls?sessionId=' + session.id)).reverse();   // oldest first, like minutes
    const sections = [];
    for (const p of polls) sections.push(await pollSection(p));

    report.replaceChildren(
      el('h1', {}, session.name),
      el('div', { class: 'meta' },
        (session.status === 'ACTIVE' ? 'Active session' : 'Ended session') + ' · started by ' + session.startedBy
          + ' on ' + when(session.startedAt) + (session.endedAt ? ' · ended ' + when(session.endedAt) : '')),
      el('div', { class: 'meta', style: 'margin-bottom:1rem' }, session.pollCount + ' vote' + (session.pollCount === 1 ? '' : 's')),
      ...(sections.length ? sections : [el('p', {}, 'This session has no votes.')]),
      el('div', { class: 'meta', style: 'margin-top:1rem' }, 'Generated by ' + me.username + ' on ' + new Date().toLocaleString()));

    const csv = document.getElementById('csv');
    csv.href = '/api/sessions/' + session.id + '/export.csv';
    csv.hidden = false;
    const print = document.getElementById('print');
    print.hidden = false;
    print.addEventListener('click', () => window.print());
  } catch (e) {
    report.textContent = e.message;
  }
})();
