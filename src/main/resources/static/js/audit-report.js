/*
 * Printable audit log: every entry that matches the search, oldest first, ready for "Print / Save as PDF"
 * (the browser's own print dialog renders every character correctly). Uses the same query parameters as the
 * audit page, so it exports exactly what was searched. Capped so a huge log cannot freeze the browser.
 */

const MAX_ROWS = 5000;
const BATCH = 200;

(async function main() {
  const me = await initPage();
  const report = document.getElementById('report');
  if (me.role !== 'ADMIN') { location.href = '/'; return; }

  const q = new URLSearchParams(location.search);
  try {
    const all = [];
    let beforeId = null;
    for (;;) {
      const page = new URLSearchParams(q);
      page.set('limit', BATCH);
      if (beforeId) page.set('beforeId', beforeId);
      const entries = await api.get('/api/audit?' + page);
      all.push(...entries);
      if (entries.length < BATCH || all.length >= MAX_ROWS) break;
      beforeId = entries[entries.length - 1].id;
    }
    const truncated = all.length >= MAX_ROWS;
    const rows = all.slice(0, MAX_ROWS).reverse();   // oldest first, like a ledger

    const lastDayIncluded = (iso) => {       // `to` is exclusive: show the last day that is really included
      const d = new Date(iso);
      d.setDate(d.getDate() - 1);
      return fmtDate(d);
    };
    const criteria = [
      q.get('from') ? 'from ' + fmtDate(q.get('from')) : null,
      q.get('to') ? 'to ' + lastDayIncluded(q.get('to')) : null,
      q.get('user') ? 'user "' + q.get('user') + '"' : null,
      q.get('action') ? 'action "' + (LABELS[q.get('action')] || q.get('action')) + '"' : null,
    ].filter(Boolean);

    report.replaceChildren(
      el('h1', {}, 'Audit log'),
      el('div', { class: 'meta' }, criteria.length ? 'Filters: ' + criteria.join(', ') : 'No filters: every entry'),
      el('div', { class: 'meta', style: 'margin-bottom:1rem' },
        rows.length + (rows.length === 1 ? ' entry' : ' entries')
          + (truncated ? ' (only the newest ' + MAX_ROWS + ' are shown: narrow the search)' : '')),
      el('table', { class: 'audit-table' },
        el('thead', {}, el('tr', {}, ...['When', 'Who', 'Action', 'Details', 'IP'].map((h) => el('th', {}, h)))),
        el('tbody', {}, ...(rows.length ? rows.map((e) => el('tr', {},
          el('td', {}, fmtDateTime(e.occurredAt)),
          el('td', {}, e.actorName || '—'),
          el('td', {}, LABELS[e.action] || e.action),
          el('td', {}, e.details || ''),
          el('td', {}, e.ip || ''))) : [el('tr', {}, el('td', { colspan: 5 }, 'No entries match.'))]))),
      el('div', { class: 'meta', style: 'margin-top:1rem' },
        'Generated by ' + me.displayName + ' on ' + fmtDateTime(new Date())));

    const print = document.getElementById('print');
    print.hidden = false;
    print.addEventListener('click', () => window.print());
  } catch (e) {
    report.textContent = e.message;
  }
})();
